B(("h3", "3.10.5. Файл подкачки"))
B(("p", "Kaspersky Security Center требует включённого swap объёмом не менее 1,5 × ОЗУ. "
        "Для 8 ГБ ОЗУ создайте файл 12 ГБ (для 16 ГБ — 24 ГБ)."))
B(("code", [
    "swapoff -a",
    "sed -i '/swap/d' /etc/fstab",
    "fallocate -l 12G /swapfile",
    "chmod 600 /swapfile",
    "mkswap /swapfile",
    "swapon /swapfile",
    "echo '/swapfile none swap sw 0 0' >> /etc/fstab",
    "free -h",
]))
B(("p", "Дополнительно задайте умеренную агрессивность выгрузки (необязательно, но рекомендуется):"))
B(("code", [
    "printf 'vm.swappiness=10\\nvm.vfs_cache_pressure=50\\n' > /etc/sysctl.d/99-ksc.conf",
    "sysctl --system",
]))

