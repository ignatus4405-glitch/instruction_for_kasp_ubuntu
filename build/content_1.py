    "ufw allow 22/tcp comment 'SSH administration'",
    "ufw allow 8080/tcp comment 'KSC Web Console'",
    "ufw allow 13000/tcp comment 'KSC Admin Server TLS'",
    "ufw allow 13000/udp comment 'KSC shutdown notifications'",
    "ufw allow from 192.168.10.0/24 to any port 13299 proto tcp comment 'Web Console/OpenAPI'",
    "ufw --force enable",
